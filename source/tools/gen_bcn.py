"""Mechanically extracts bcdec.h's BC6H/BC7 partition tables and BC6H mode
bit-layout switch into Java source fragments (no hand-typing of tables)."""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1]).read_text()
out = pathlib.Path(sys.argv[2])

def body_of(start_marker):
    i = src.index(start_marker)
    return src[i:]

def parse_table(text, start_marker):
    i = text.index(start_marker)
    j = text.index("};", i)
    block = text[i:j]
    block = re.sub(r"/\*.*?\*/", "", block, flags=re.S)
    nums = [int(n) for n in re.findall(r"\b\d+\b", block.split("=", 1)[1])]
    return nums

bc6 = body_of("BCDECDEF void bcdec_bc6h_half(")
bc7 = body_of("BCDECDEF void bcdec_bc7(")

p6 = parse_table(bc6, "static unsigned char partition_sets[32][4][4]")
assert len(p6) == 32 * 16, len(p6)
p7 = parse_table(bc7, "static unsigned char partition_sets[2][64][4][4]")
assert len(p7) == 2 * 64 * 16, len(p7)

def java_table(name, nums, rows):
    per = len(nums) // rows
    lines = [f"    static final int[][] {name} = {{"]
    for r in range(rows):
        chunk = nums[r * per:(r + 1) * per]
        lines.append("        {" + ", ".join(str(n) for n in chunk) + "},")
    lines.append("    };")
    return "\n".join(lines)

# BC6H mode switch: from "switch (mode) {" up to "default: {"
s = bc6.index("switch (mode) {")
e = bc6.index("default: {", s)
sw = bc6[s + len("switch (mode) {"):e]
sw = re.sub(r"/\*.*?\*/", "", sw, flags=re.S)
sw = sw.replace("bcdec__bitstream_read_bits_r(&bstream, ", "bs.bitsReversed(")
sw = sw.replace("bcdec__bitstream_read_bits(&bstream, ", "bs.bits(")
sw = sw.replace("bcdec__bitstream_read_bit(&bstream)", "bs.bits(1)")
sw = re.sub(r"case (0b[01]+): \{", r"case \1 -> {", sw)
sw = re.sub(r"\}\s*break;", "}", sw)
sw = "\n".join(line.rstrip() for line in sw.splitlines() if line.strip())

parts = [
    "// ---- generated by gen_bcn.py from bcdec.h (MIT/Unlicense) -- do not edit by hand ----",
    java_table("BC6H_PARTITIONS", p6, 32),
    java_table("BC7_PARTITIONS_2", p7[:64 * 16], 64),
    java_table("BC7_PARTITIONS_3", p7[64 * 16:], 64),
    "    // BC6H mode switch body:",
    sw,
]
out.write_text("\n".join(parts) + "\n")
print("ok", len(p6), len(p7), sw.count("case "))
